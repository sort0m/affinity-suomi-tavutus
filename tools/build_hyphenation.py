"""Build the small Affinity/libhyphen dictionary; no third-party dependencies."""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "hyphenation_patterns.txt"
OUTPUT = ROOT / "hyph_fi_FI.dic"


def parse_pattern(pattern):
    letters, weights = "", [0]
    for char in pattern:
        if char in "0123456789":
            weights[-1] = int(char)
        else:
            letters += char
            weights.append(0)
    return letters, weights


def read_patterns(path=SOURCE):
    patterns = {}
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        pattern = line.split("%", 1)[0].strip()
        if not pattern:
            continue
        if not re.fullmatch(r"[.a-zäöå0-9]+", pattern):
            raise ValueError(f"{path}:{number}: invalid pattern: {pattern!r}")
        key, weights = parse_pattern(pattern)
        if not key or not any(weights):
            raise ValueError(f"{path}:{number}: empty pattern or weights")
        previous = patterns.setdefault(key, [0] * len(weights))
        patterns[key] = [max(a, b) for a, b in zip(previous, weights)]
    return patterns


def prepare(patterns):
    """Merge suffix matches at EVERY trie prefix for libhyphen's state machine.

    Simply writing raw TeX patterns silently loses overlapping matches. This
    performs the substring preparation described by hunspell/hyphen's
    README.hyphen, including nonterminal prefixes (e.g. 'ab' in 'abcd').
    """
    prefixes = {key[:end] for key in patterns for end in range(1, len(key) + 1)}
    prepared = {}
    for prefix in sorted(prefixes):
        combined = [0] * (len(prefix) + 1)
        for start in range(len(prefix)):
            suffix = patterns.get(prefix[start:])
            if suffix is not None:
                for offset, weight in enumerate(suffix, start):
                    combined[offset] = max(combined[offset], weight)
        if any(combined):
            prepared[prefix] = combined
    return prepared


def render(patterns):
    lines = [
        "UTF-8",
        "LEFTHYPHENMIN 2",
        "RIGHTHYPHENMIN 2",
        "% Generated by tools/build_hyphenation.py; edit hyphenation_patterns.txt.",
    ]
    for key, weights in prepare(patterns).items():
        line = str(weights[0]) if weights[0] else ""
        for char, weight in zip(key, weights[1:]):
            line += char + (str(weight) if weight else "")
        lines.append(line)
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    patterns = read_patterns()
    data = render(patterns)
    OUTPUT.write_text(data, encoding="utf-8", newline="\n")
    print(f"{OUTPUT.name}: {len(data.encode('utf-8'))} bytes, "
          f"{len(prepare(patterns))} prepared patterns")
